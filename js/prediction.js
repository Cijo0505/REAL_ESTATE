
document.addEventListener("DOMContentLoaded", function () {

    const form = document.getElementById("predictionForm");
    const result = document.getElementById("predictionResult");
    const message = document.getElementById("predictionMessage");
    const button = document.getElementById("predictButton");

    form.addEventListener("submit", async function (event) {
        event.preventDefault();

        const property = {
            city: document.getElementById("city").value,
            area: Number(document.getElementById("area").value),
            bedrooms: Number(
                document.getElementById("bedrooms").value
            ),
            bathrooms: Number(
                document.getElementById("bathrooms").value
            ),
            property_type:
                document.getElementById("propertyType").value,
            property_age: Number(
                document.getElementById("propertyAge").value
            )
        };

        message.textContent = "";

        if (!form.reportValidity()) return;

        if (property.area < 200 || property.area > 10000) {
            message.textContent = "Enter a valid property area.";
            return;
        }

        button.disabled = true;
        button.textContent = "Predicting...";

        result.textContent = "Calculating...";

        try {
            const response = await fetch(
                "http://127.0.0.1:5000/predict",
                {
                    method: "POST",
                    headers: {
                        "Content-Type": "application/json"
                    },
                    body: JSON.stringify(property)
                }
            );

            const data = await response.json();

            if (!response.ok) {
                throw new Error(
                    data.error || "Prediction failed."
                );
            }

            const formattedPrice = new Intl.NumberFormat(
                "en-IN",
                {
                    style: "currency",
                    currency: "INR",
                    maximumFractionDigits: 0
                }
            ).format(data.predicted_price);

            result.textContent = formattedPrice;

            message.textContent =
                "Estimated price generated by the ML model.";

            message.style.color = "#15803d";

        } catch (error) {
            result.textContent = "Prediction unavailable";

            message.style.color = "#dc2626";

            message.textContent =
                error.message +
                " Check that the Flask server is running.";
        } finally {
            button.disabled = false;
            button.textContent = "Predict House Price";
        }
    });

});